/**
 * ### [Gateway Intents](https://discord.com/developers/docs/events/gateway#gateway-intents)
 *
 * Bitwise values passed as `intents` when identifying. An intent you don't
 * request means you receive **none** of its events.
 *
 * Three intents are **privileged** and must be enabled for your app in the
 * Developer Portal (and approved after verification for apps in 100+ guilds):
 * `GUILD_PRESENCES`, `GUILD_MEMBERS`, and `MESSAGE_CONTENT`. Requesting one
 * you haven't been granted closes the connection with
 * {@link GatewayCloseCode.DISALLOWED_INTENTS | 4014}.
 */
