/**
 * ### [Gateway Intents](https://discord.com/developers/docs/events/gateway#gateway-intents)
 */
export const gatewayIntentsSchema = v.enum_(GatewayIntents);
export const gatewayIntent = bitfield(
  `gatewayIntent`,
  GatewayIntents,
  `Invalid Gateway Intent`
);

/** A single intent's name. */
export type GatewayIntentName = keyof typeof GatewayIntents;

/**
 * The privileged intents. Requesting one your app hasn't been granted is a
 * connection-fatal `4014`, so these are worth surfacing distinctly.
 */
export const PRIVILEGED_INTENTS = [
  `GUILD_PRESENCES`,
  `GUILD_MEMBERS`,
  `MESSAGE_CONTENT`
] as const satisfies readonly GatewayIntentName[];

